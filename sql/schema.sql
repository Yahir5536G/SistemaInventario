-- Sistema de Inventario: esquema completo
-- Ejecutar completo en Supabase -> SQL Editor.
-- Es repetible: se puede ejecutar varias veces sin errores ni duplicados.
-- Orden: categorias -> productos (productos depende de categorias).

-- 1. Tabla categorias

create table if not exists public.categorias (
  id bigint generated by default as identity not null,
  nombre text not null,
  descripcion text null,
  creado_en timestamp with time zone not null default now(),
  constraint categorias_pkey primary key (id),
  constraint categorias_descripcion_longitud check (
    (
      (descripcion is null)
      or (char_length(descripcion) <= 500)
    )
  ),
  constraint categorias_nombre_longitud check ((char_length(nombre) <= 100)),
  constraint categorias_nombre_no_vacio check ((length(btrim(nombre)) > 0))
);

-- Nombre único sin distinguir mayúsculas 
create unique index if not exists categorias_nombre_unico on public.categorias using btree (lower(nombre));


-- 2. Tabla productos (cada producto pertenece a una categoría)

create table if not exists public.productos (
  id bigint generated by default as identity not null,
  nombre text not null,
  descripcion text null,
  precio numeric(12, 2) not null default 0,
  cantidad integer not null default 0,
  categoria_id bigint not null,
  creado_en timestamp with time zone not null default now(),
  constraint productos_pkey primary key (id),
  -- Relación uno a muchos. restrict: no se puede borrar una categoría
  -- que todavía tiene productos.
  constraint productos_categoria_id_fkey foreign key (categoria_id)
    references public.categorias (id) on update cascade on delete restrict,
  constraint productos_cantidad_check check ((cantidad >= 0)),
  constraint productos_nombre_no_vacio check ((length(btrim(nombre)) > 0)),
  constraint productos_precio_check check ((precio >= (0)::numeric)),
  constraint productos_nombre_longitud check ((char_length(nombre) <= 100)),
  constraint productos_descripcion_longitud check (
    (
      (descripcion is null)
      or (char_length(descripcion) <= 500)
    )
  )
);

-- Acelera la unión con categorias y la comprobación de la llave foránea.
create index if not exists productos_categoria_id_idx on public.productos using btree (categoria_id);

-- 3. Seguridad: RLS (Row Level Security)

grant usage on schema public to anon;
grant select, insert, update, delete
    on public.categorias, public.productos to anon;

alter table public.categorias enable row level security;
alter table public.productos  enable row level security;

-- Lectura pública.
drop policy if exists "leer categorias" on public.categorias;
create policy "leer categorias" on public.categorias
    for select to anon using (true);

drop policy if exists "leer productos" on public.productos;
create policy "leer productos" on public.productos
    for select to anon using (true);

-- Escritura sin inicio de sesión
drop policy if exists "escribir categorias" on public.categorias;
create policy "escribir categorias" on public.categorias
    for all to anon using (true) with check (true);

drop policy if exists "escribir productos" on public.productos;
create policy "escribir productos" on public.productos
    for all to anon using (true) with check (true);

